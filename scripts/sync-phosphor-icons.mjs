import { copyFile, mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const theme = join(root, 'ghost/Headline-main')
const packageRoot = join(root, 'node_modules/@phosphor-icons/web')
const destination = join(theme, 'assets/built')

async function templates(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = await Promise.all(entries.map(entry => {
    const path = join(directory, entry.name)
    if (entry.isDirectory() && !['node_modules', 'assets', 'dist'].includes(entry.name)) return templates(path)
    return entry.isFile() && entry.name.endsWith('.hbs') ? [path] : []
  }))
  return files.flat()
}

// Ghost ships as a standalone theme, so bundle its fonts without a CDN dependency.
const sources = await Promise.all((await templates(theme)).map(path => readFile(path, 'utf8')))
const icons = new Set(sources.flatMap(source => Array.from(source.matchAll(/\bph-[a-z0-9-]+\b/g), match => match[0])))
for (const weight of ['ph-fill', 'ph-light']) icons.delete(weight)

await mkdir(join(destination, 'fonts'), { recursive: true })
const styles = ['/* Generated by npm run icons:sync from @phosphor-icons/web. */']
for (const [weight, base, family] of [
  ['regular', 'ph', 'Phosphor'],
  ['fill', 'ph-fill', 'Phosphor-Fill'],
  ['light', 'ph-light', 'Phosphor-Light'],
]) {
  const directory = join(packageRoot, 'src', weight)
  const source = await readFile(join(directory, 'style.css'), 'utf8')
  const face = source.match(/@font-face\s*\{[\s\S]*?\}/)?.[0]
  const baseRule = source.match(new RegExp(`\\.${base} \\{[\\s\\S]*?\\}`))?.[0]
  if (!face || !baseRule) throw new Error(`Missing Phosphor ${weight} font styles`)
  styles.push(face.replace(/src:[\s\S]*?;/, `src: url("./fonts/${family}.woff2") format("woff2");`), baseRule)
  for (const name of [...icons].sort()) {
    const glyph = source.match(new RegExp(`\\.${base}\\.${name}:before \\{[\\s\\S]*?\\}`))?.[0]
    if (!glyph) throw new Error(`Unknown Phosphor ${weight} icon: ${name}`)
    styles.push(glyph)
  }
  await copyFile(join(directory, `${family}.woff2`), join(destination, 'fonts', `${family}.woff2`))
}
await writeFile(join(destination, 'phosphor-icons.css'), `${styles.join('\n\n')}\n`)
await copyFile(join(packageRoot, 'LICENSE'), join(destination, 'fonts/Phosphor-LICENSE.txt'))
console.log(`Bundled ${icons.size} Phosphor icons in regular, fill and light for Ghost`)
